using CrmSystem.Models.Entities;
using CrmSystem.Models.Enums;
using CrmSystem.Models.Identity;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;

namespace CrmSystem.Data;

/// <summary>
/// Verifies that the EF Core model matches the SQL Server schema exactly, and that
/// the DbContext behaviours (generated code, computed reminder, soft delete, audit,
/// views, duplicate protection) really work.
///
/// Run:  dotnet run -- --verify-db
/// Everything is executed inside a transaction that is ROLLED BACK (no data left).
/// Exit code 0 = all checks passed.
/// </summary>
public static class DatabaseVerifier
{
    private sealed record DbColumn(string TableName, string ColumnName, string IsNullable, string DataType);

    public static async Task<int> RunAsync(IServiceProvider services)
    {
        using var scope = services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<ApplicationDbContext>();
        var results = new List<(bool Ok, string Name, string? Detail)>();

        void Check(bool ok, string name, string? detail = null) => results.Add((ok, name, detail));

        // ---------------------------------------------------------------
        // 1. Connection
        // ---------------------------------------------------------------
        var canConnect = await db.Database.CanConnectAsync();
        Check(canConnect, "Connect to CRMDatabase");
        if (!canConnect) return Print(results);

        // ---------------------------------------------------------------
        // 2. Every mapped table/view column exists in SQL Server
        // ---------------------------------------------------------------
        var dbColumns = await db.Database
            .SqlQueryRaw<DbColumn>(
                "SELECT TABLE_NAME AS TableName, COLUMN_NAME AS ColumnName, IS_NULLABLE AS IsNullable, DATA_TYPE AS DataType " +
                "FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'dbo'")
            .ToListAsync();
        var lookup = dbColumns.ToDictionary(c => (c.TableName.ToUpperInvariant(), c.ColumnName.ToUpperInvariant()));
        var dbObjects = dbColumns.Select(c => c.TableName.ToUpperInvariant()).ToHashSet();

        var missing = new List<string>();
        var nullMismatch = new List<string>();
        var mappedObjects = 0;

        foreach (var entityType in db.Model.GetEntityTypes())
        {
            var tableName = entityType.GetTableName() ?? entityType.GetViewName();
            if (tableName == null) continue;
            var storeObject = entityType.GetTableName() != null
                ? StoreObjectIdentifier.Table(tableName, entityType.GetSchema())
                : StoreObjectIdentifier.View(tableName, entityType.GetViewSchema());

            mappedObjects++;
            if (!dbObjects.Contains(tableName.ToUpperInvariant()))
            {
                missing.Add($"{tableName} (table/view missing)");
                continue;
            }

            foreach (var property in entityType.GetProperties())
            {
                var column = property.GetColumnName(storeObject);
                if (column == null) continue;
                if (!lookup.TryGetValue((tableName.ToUpperInvariant(), column.ToUpperInvariant()), out var dbCol))
                {
                    missing.Add($"{tableName}.{column}");
                    continue;
                }
                // Model says NOT NULL but DB allows NULL => reading a NULL would crash.
                // Computed columns are always reported nullable by SQL Server; ours are built
                // only from NOT NULL columns, so they are skipped.
                if (!property.IsNullable && dbCol.IsNullable == "YES" && entityType.FindPrimaryKey() != null
                    && property.GetComputedColumnSql() == null)
                    nullMismatch.Add($"{tableName}.{column}");
            }
        }

        Check(missing.Count == 0, $"All columns of {mappedObjects} mapped tables/views exist in SQL Server",
              missing.Count == 0 ? null : string.Join(", ", missing));
        Check(nullMismatch.Count == 0, "Nullability of required properties matches the database",
              nullMismatch.Count == 0 ? null : string.Join(", ", nullMismatch));

        // ---------------------------------------------------------------
        // 3. Every entity set can be queried (SQL generated by EF is valid)
        // ---------------------------------------------------------------
        var failedQueries = new List<string>();
        var setMethod = typeof(DbContext).GetMethod(nameof(DbContext.Set), Type.EmptyTypes)!;
        foreach (var entityType in db.Model.GetEntityTypes().Where(e => !e.IsOwned() && !e.HasSharedClrType))
        {
            try
            {
                var set = (IQueryable<object>)setMethod.MakeGenericMethod(entityType.ClrType).Invoke(db, null)!;
                await set.Take(1).ToListAsync();
            }
            catch (Exception ex)
            {
                failedQueries.Add($"{entityType.ClrType.Name}: {ex.GetBaseException().Message}");
            }
        }
        Check(failedQueries.Count == 0, "Every DbSet / view can be queried",
              failedQueries.Count == 0 ? null : string.Join(" | ", failedQueries));

        // ---------------------------------------------------------------
        // 4. Seed data present
        // ---------------------------------------------------------------
        var roleCount = await db.Roles.CountAsync();
        Check(roleCount >= 3, "Roles seeded (Admin, SalesManager, SalesEmployee)", $"{roleCount} roles");
        var typeCount = await db.ActivityTypes.CountAsync(t => t.IsSystem);
        Check(typeCount == 9, "9 system activity types seeded", $"{typeCount} types");
        var settingCount = await db.SystemSettings.CountAsync();
        Check(settingCount >= 28, "System settings seeded", $"{settingCount} settings");

        // ---------------------------------------------------------------
        // 5. Behaviour round-trip inside a transaction (rolled back)
        // ---------------------------------------------------------------
        var strategy = db.Database.CreateExecutionStrategy();
        await strategy.ExecuteAsync(async () =>
        {
            await using var tx = await db.Database.BeginTransactionAsync();
            try
            {
                var user = new ApplicationUser
                {
                    Id = Guid.NewGuid().ToString(),
                    UserName = "verify.user",
                    NormalizedUserName = "VERIFY.USER." + Guid.NewGuid().ToString("N"),
                    Email = "verify@test.local",
                    NormalizedEmail = "VERIFY@TEST.LOCAL",
                    FullName = "Verify User",
                    SecurityStamp = Guid.NewGuid().ToString()
                };
                db.Users.Add(user);
                await db.SaveChangesAsync();

                // Client: code generated by SQL, name cleaned, NormalizedName computed
                var client = new Client { CompanyName = "  Verify   Test  Company ", AccountManagerId = user.Id };
                db.Clients.Add(client);
                await db.SaveChangesAsync();
                Check(client.ClientId > 0 && client.CompanyCode?.StartsWith("CL-") == true,
                      "EF insert: CompanyCode generated by SQL Server", client.CompanyCode);
                Check(client.CompanyName == "Verify Test Company" && client.NormalizedName == "VERIFY TEST COMPANY",
                      "Company name cleaned + NormalizedName computed", $"'{client.CompanyName}' / '{client.NormalizedName}'");
                Check(client.CreatedAt > DateTime.UtcNow.AddMinutes(-5) && client.RowVersion.Length == 8,
                      "CreatedAt filled automatically + RowVersion returned");

                // Duplicate name blocked by unique index
                db.Clients.Add(new Client { CompanyName = "verify test company" });
                try
                {
                    await db.SaveChangesAsync();
                    Check(false, "Duplicate company name rejected through EF");
                }
                catch (DbUpdateException)
                {
                    Check(true, "Duplicate company name rejected through EF");
                }
                foreach (var e in db.ChangeTracker.Entries<Client>().Where(e => e.State == EntityState.Added).ToList())
                    e.State = EntityState.Detached;

                // Contact + activity + follow-up
                var contact = new Contact { ClientId = client.ClientId, FullName = "Ahmed", IsPrimary = true };
                db.Contacts.Add(contact);
                var activity = new Activity
                {
                    ClientId = client.ClientId,
                    Contact = contact,
                    ActivityTypeId = ActivityTypeIds.ColdCall,
                    ActivityDate = new DateOnly(2026, 11, 10),
                    Notes = "Contacted the company regarding receiving motors. They will send an email within two days.",
                    Outcome = "Waiting for Email",
                    PerformedById = user.Id
                };
                db.Activities.Add(activity);

                var followUp = new FollowUp
                {
                    ClientId = client.ClientId,
                    Contact = contact,
                    FollowUpTypeId = ActivityTypeIds.ColdCall,
                    SourceActivity = activity,
                    Description = "Contact the company to check the motor delivery status.",
                    AssignedToId = user.Id,
                    Priority = FollowUpPriority.High
                };
                followUp.SetSchedule(new DateOnly(2026, 11, 15), new TimeOnly(10, 0), "Asia/Muscat");
                db.FollowUps.Add(followUp);
                await db.SaveChangesAsync();

                Check(followUp.DueAtUtc == new DateTime(2026, 11, 15, 6, 0, 0),
                      "SetSchedule: 15/11 10:00 Muscat = 06:00 UTC", followUp.DueAtUtc.ToString("yyyy-MM-dd HH:mm"));
                Check(followUp.ReminderAtUtc == new DateTime(2026, 11, 14, 6, 0, 0),
                      "Computed ReminderAtUtc read back = 14/11 06:00 UTC (10:00 Muscat)", followUp.ReminderAtUtc.ToString("yyyy-MM-dd HH:mm"));

                // Reschedule re-arms the reminder
                followUp.ReminderStatus = ReminderStatus.Sent;
                followUp.ReminderSentAtUtc = DateTime.UtcNow;
                await db.SaveChangesAsync();
                followUp.SetSchedule(new DateOnly(2026, 11, 16), new TimeOnly(10, 0));
                await db.SaveChangesAsync();
                await db.Entry(followUp).ReloadAsync();
                Check(followUp.ReminderStatus == ReminderStatus.Scheduled && followUp.ReminderAtUtc == new DateTime(2026, 11, 15, 6, 0, 0),
                      "Reschedule re-arms reminder and moves ReminderAtUtc", followUp.ReminderAtUtc.ToString("yyyy-MM-dd HH:mm"));

                // Notification dedup through EF
                var key = Notification.FollowUpReminderKey(followUp.FollowUpId, followUp.DueAtUtc, user.Id);
                db.Notifications.Add(new Notification { UserId = user.Id, NotificationType = NotificationType.FollowUpReminder, Title = "t", Message = "m", DedupKey = key });
                await db.SaveChangesAsync();
                db.Notifications.Add(new Notification { UserId = user.Id, NotificationType = NotificationType.FollowUpReminder, Title = "t", Message = "m", DedupKey = key });
                try
                {
                    await db.SaveChangesAsync();
                    Check(false, "Duplicate notification (DedupKey) rejected through EF");
                }
                catch (DbUpdateException)
                {
                    Check(true, "Duplicate notification (DedupKey) rejected through EF");
                }
                foreach (var e in db.ChangeTracker.Entries<Notification>().Where(e => e.State == EntityState.Added).ToList())
                    e.State = EntityState.Detached;

                // Soft delete: Remove() => IsDeleted, hidden by query filter
                var extra = new Contact { ClientId = client.ClientId, FullName = "Temporary Contact" };
                db.Contacts.Add(extra);
                await db.SaveChangesAsync();
                db.Contacts.Remove(extra);
                await db.SaveChangesAsync();
                var visible = await db.Contacts.AnyAsync(c => c.ContactId == extra.ContactId);
                var stored = await db.Contacts.IgnoreQueryFilters().AsNoTracking().FirstOrDefaultAsync(c => c.ContactId == extra.ContactId);
                Check(!visible && stored is { IsDeleted: true, DeletedAt: not null },
                      "Remove() = soft delete; row kept and hidden by query filter");

                // Audit log rows
                var audits = await db.AuditLogs.AsNoTracking()
                    .Where(a => a.EntityName == nameof(Client) && a.EntityId == client.ClientId.ToString())
                    .ToListAsync();
                Check(audits.Any(a => a.Action == "Create" && a.NewValues!.Contains("Verify Test Company")),
                      "AuditLogs row written on Create (with JSON values)", $"{audits.Count} rows");
                var softDeleteAudit = await db.AuditLogs.AnyAsync(a => a.EntityName == nameof(Contact) && a.EntityId == extra.ContactId.ToString() && a.Action == "SoftDelete");
                Check(softDeleteAudit, "AuditLogs row written on SoftDelete");

                // Update audit records old/new values
                client.City = "Muscat";
                await db.SaveChangesAsync();
                var updateAudit = await db.AuditLogs.AsNoTracking()
                    .Where(a => a.EntityName == nameof(Client) && a.EntityId == client.ClientId.ToString() && a.Action == "Update")
                    .FirstOrDefaultAsync();
                // The verifier runs without a signed-in user, like a background job:
                // the change is audited but UpdatedAt (= last USER edit) stays untouched.
                Check(updateAudit?.NewValues?.Contains("Muscat") == true && client.UpdatedAt == null,
                      "Update audits changed column only; background jobs leave UpdatedAt untouched", updateAudit?.NewValues);

                // Optimistic concurrency (RowVersion)
                var before = client.RowVersion.ToArray();
                await db.Database.ExecuteSqlInterpolatedAsync($"UPDATE dbo.Clients SET Phone = N'000' WHERE ClientId = {client.ClientId}");
                client.Website = "https://example.com";
                try
                {
                    await db.SaveChangesAsync();
                    Check(false, "Concurrent edit detected (RowVersion)");
                }
                catch (DbUpdateConcurrencyException)
                {
                    Check(true, "Concurrent edit detected (RowVersion)");
                }
                db.Entry(client).State = EntityState.Detached;

                // Views
                var summary = await db.ClientSummaries.AsNoTracking().FirstOrDefaultAsync(s => s.ClientId == client.ClientId);
                Check(summary is { LastActivityDate: not null, PrimaryContactName: "Ahmed", TotalActivities: 1 }
                      && summary.NextFollowUpDate == new DateOnly(2026, 11, 16),
                      "vw_ClientSummary via EF (last contact, next follow-up, primary contact)");

                var fuView = await db.FollowUpDetails.AsNoTracking().FirstOrDefaultAsync(f => f.FollowUpId == followUp.FollowUpId);
                Check(fuView != null && fuView.SourceActivityOutcome == "Waiting for Email" && fuView.CompanyName == "Verify Test Company",
                      "vw_FollowUpDetails via EF (with previous activity)");

                var timeline = await db.ClientTimeline.AsNoTracking()
                    .Where(t => t.ClientId == client.ClientId)
                    .OrderByDescending(t => t.EventAtLocal).ThenByDescending(t => t.SortKey)
                    .ToListAsync();
                Check(timeline.Count == 2 && timeline[0].EventKind == "FollowUp" && timeline[1].EventKind == "Activity",
                      "vw_ClientTimeline via EF (descending order)", string.Join(", ", timeline.Select(t => $"{t.EventAtLocal:dd/MM} {t.EventKind}")));

                var actView = await db.ActivityDetails.AsNoTracking().FirstOrDefaultAsync(a => a.ActivityId == activity.ActivityId);
                Check(actView is { ActivityTypeCode: "COLD_CALL", PerformedByName: "Verify User", ContactName: "Ahmed" },
                      "vw_ActivityDetails via EF");
            }
            catch (Exception ex)
            {
                Check(false, "Round-trip test crashed", ex.GetBaseException().Message);
            }
            finally
            {
                await tx.RollbackAsync();
            }
        });

        // Sequence / identity values are not transactional: reset on a fresh database.
        await db.Database.ExecuteSqlRawAsync(@"
            IF NOT EXISTS (SELECT 1 FROM dbo.Clients) ALTER SEQUENCE dbo.Seq_ClientCode RESTART WITH 1;
            IF NOT EXISTS (SELECT 1 FROM dbo.Clients)       DBCC CHECKIDENT ('dbo.Clients', RESEED, 0) WITH NO_INFOMSGS;
            IF NOT EXISTS (SELECT 1 FROM dbo.Contacts)      DBCC CHECKIDENT ('dbo.Contacts', RESEED, 0) WITH NO_INFOMSGS;
            IF NOT EXISTS (SELECT 1 FROM dbo.Activities)    DBCC CHECKIDENT ('dbo.Activities', RESEED, 0) WITH NO_INFOMSGS;
            IF NOT EXISTS (SELECT 1 FROM dbo.FollowUps)     DBCC CHECKIDENT ('dbo.FollowUps', RESEED, 0) WITH NO_INFOMSGS;
            IF NOT EXISTS (SELECT 1 FROM dbo.Notifications) DBCC CHECKIDENT ('dbo.Notifications', RESEED, 0) WITH NO_INFOMSGS;
            IF NOT EXISTS (SELECT 1 FROM dbo.AuditLogs)     DBCC CHECKIDENT ('dbo.AuditLogs', RESEED, 0) WITH NO_INFOMSGS;");

        return Print(results);
    }

    private static int Print(List<(bool Ok, string Name, string? Detail)> results)
    {
        Console.OutputEncoding = System.Text.Encoding.UTF8;
        Console.WriteLine();
        Console.WriteLine("================ DATABASE VERIFICATION ================");
        var i = 1;
        foreach (var (ok, name, detail) in results)
        {
            Console.ForegroundColor = ok ? ConsoleColor.Green : ConsoleColor.Red;
            Console.Write(ok ? "PASS " : "FAIL ");
            Console.ResetColor();
            Console.WriteLine($"{i++,2}. {name}{(string.IsNullOrEmpty(detail) ? "" : "  -> " + detail)}");
        }
        var failed = results.Count(r => !r.Ok);
        Console.WriteLine("=======================================================");
        Console.WriteLine(failed == 0
            ? $"ALL {results.Count} CHECKS PASSED (test data rolled back)."
            : $"{failed} of {results.Count} CHECKS FAILED.");
        return failed == 0 ? 0 : 1;
    }
}
